import React, { useEffect, useState } from 'react';
import { supabase } from '../utils/supabase/client';
import { Database, Plus, CheckCircle, AlertCircle, RefreshCw, Trash2, ExternalLink } from 'lucide-react';

interface Todo {
  id: number | string;
  name?: string;
  title?: string;
  is_complete?: boolean;
  created_at?: string;
}

export default function TodosPage() {
  const [todos, setTodos] = useState<Todo[]>([]);
  const [loading, setLoading] = useState<boolean>(true);
  const [error, setError] = useState<string | null>(null);
  const [newTodoName, setNewTodoName] = useState('');
  const [submitting, setSubmitting] = useState(false);

  const fetchTodos = async () => {
    setLoading(true);
    setError(null);
    try {
      const { data, error: err } = await supabase
        .from('todos')
        .select('*')
        .order('id', { ascending: true });

      if (err) {
        setError(err.message);
      } else {
        setTodos(data || []);
      }
    } catch (err: unknown) {
      const message = err instanceof Error ? err.message : 'Failed to connect to Supabase';
      setError(message);
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    fetchTodos();
  }, []);

  const handleAddTodo = async (e: React.FormEvent) => {
    e.preventDefault();
    if (!newTodoName.trim() || submitting) return;

    setSubmitting(true);
    try {
      const { data, error: err } = await supabase
        .from('todos')
        .insert([{ name: newTodoName.trim() }])
        .select();

      if (err) {
        alert(`Error inserting todo: ${err.message}`);
      } else if (data) {
        setTodos((prev) => [...prev, ...data]);
        setNewTodoName('');
      }
    } catch (err: unknown) {
      alert(err instanceof Error ? err.message : 'Error adding todo');
    } finally {
      setSubmitting(false);
    }
  };

  const handleDeleteTodo = async (id: number | string) => {
    try {
      const { error: err } = await supabase.from('todos').delete().eq('id', id);
      if (err) {
        alert(err.message);
      } else {
        setTodos((prev) => prev.filter((t) => t.id !== id));
      }
    } catch (err: unknown) {
      alert(err instanceof Error ? err.message : 'Error deleting todo');
    }
  };

  return (
    <div className="p-6 max-w-4xl mx-auto space-y-6">
      {/* Header */}
      <div className="flex flex-col sm:flex-row items-start sm:items-center justify-between gap-4 p-6 bg-slate-900/80 border border-slate-800 rounded-xl backdrop-blur-md shadow-lg">
        <div className="flex items-center space-x-3">
          <div className="p-3 bg-emerald-500/10 border border-emerald-500/20 rounded-lg text-emerald-400">
            <Database className="w-6 h-6" />
          </div>
          <div>
            <h1 className="text-xl font-bold text-white flex items-center gap-2">
              Supabase Integration
              <span className="px-2 py-0.5 text-xs font-medium bg-emerald-500/20 text-emerald-300 border border-emerald-500/30 rounded-full">
                Active
              </span>
            </h1>
            <p className="text-xs text-slate-400 mt-0.5">
              Connected to <code className="text-slate-300">butmxdropiechrqapkte.supabase.co</code>
            </p>
          </div>
        </div>
        <button
          onClick={fetchTodos}
          disabled={loading}
          className="flex items-center gap-2 px-3 py-2 text-xs font-medium text-slate-300 bg-slate-800 hover:bg-slate-700 border border-slate-700 rounded-lg transition-colors"
        >
          <RefreshCw className={`w-3.5 h-3.5 ${loading ? 'animate-spin' : ''}`} />
          Refresh
        </button>
      </div>

      {/* Error / Table hint banner if table not yet created */}
      {error && (
        <div className="p-4 bg-amber-950/40 border border-amber-800/60 rounded-xl text-amber-200 space-y-2">
          <div className="flex items-center gap-2 text-sm font-semibold">
            <AlertCircle className="w-4 h-4 text-amber-400 shrink-0" />
            Supabase Notice: {error}
          </div>
          <p className="text-xs text-amber-300/80 leading-relaxed">
            If you haven't created the <code className="bg-slate-900 px-1.5 py-0.5 rounded text-amber-300">todos</code> table yet in Supabase, run this in your Supabase SQL Editor:
          </p>
          <pre className="p-3 bg-slate-950/80 border border-slate-800 text-slate-300 text-xs rounded-lg overflow-x-auto font-mono">
{`create table todos (
  id bigint generated by default as identity primary key,
  name text not null,
  is_complete boolean default false,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Enable Row Level Security (optional) or allow read/write:
alter table todos enable row level security;
create policy "Allow all operations for public" on todos for all using (true);`}
          </pre>
        </div>
      )}

      {/* Add Todo Form */}
      <form onSubmit={handleAddTodo} className="flex gap-2">
        <input
          type="text"
          value={newTodoName}
          onChange={(e) => setNewTodoName(e.target.value)}
          placeholder="Enter todo item name..."
          className="flex-1 px-4 py-2.5 bg-slate-900/80 border border-slate-800 rounded-lg text-sm text-white placeholder-slate-500 focus:outline-none focus:border-emerald-500 transition-colors"
        />
        <button
          type="submit"
          disabled={submitting || !newTodoName.trim()}
          className="flex items-center gap-2 px-4 py-2.5 bg-emerald-600 hover:bg-emerald-500 disabled:opacity-50 text-white text-sm font-medium rounded-lg transition-colors"
        >
          <Plus className="w-4 h-4" />
          Add Item
        </button>
      </form>

      {/* Todo List */}
      <div className="bg-slate-900/60 border border-slate-800 rounded-xl overflow-hidden shadow-lg">
        <div className="px-5 py-3.5 border-b border-slate-800 text-xs font-semibold uppercase tracking-wider text-slate-400 flex justify-between items-center">
          <span>Items from `todos` table ({todos.length})</span>
          {loading && <span className="text-emerald-400 font-mono lowercase">syncing...</span>}
        </div>

        {loading && todos.length === 0 ? (
          <div className="p-8 text-center text-slate-500 text-sm">
            <RefreshCw className="w-5 h-5 mx-auto mb-2 animate-spin text-slate-400" />
            Loading todos from Supabase...
          </div>
        ) : todos.length === 0 ? (
          <div className="p-8 text-center text-slate-500 text-sm">
            No todos found in Supabase. Add one above or insert records in the Supabase Dashboard.
          </div>
        ) : (
          <ul className="divide-y divide-slate-800/80">
            {todos.map((todo) => (
              <li
                key={String(todo.id)}
                className="px-5 py-3.5 flex items-center justify-between hover:bg-slate-800/40 transition-colors"
              >
                <div className="flex items-center gap-3">
                  <CheckCircle className="w-4 h-4 text-emerald-400" />
                  <span className="text-sm text-slate-200">
                    {todo.name || todo.title || `Item #${todo.id}`}
                  </span>
                </div>
                <button
                  onClick={() => handleDeleteTodo(todo.id)}
                  className="p-1.5 text-slate-500 hover:text-rose-400 rounded transition-colors"
                  title="Delete"
                >
                  <Trash2 className="w-4 h-4" />
                </button>
              </li>
            ))}
          </ul>
        )}
      </div>
    </div>
  );
}
